/* Метка e2e: на живом сайте счётчик не должен считать прогон робота за человека.
   Локальный сервер метку не несёт — там endpoint метрики всё равно отвечает 404. */
const U = (path) => (LIVE ? `${BASE}${path}?e2e=1` : `${BASE}${path}`);

/* Прод-раскладка: index/privacy/robots/sitemap в корне, лендинги из seo/*.html
   тоже в корне (на живом сайте /csv-to-json-for-gst.html), плюс css, js, vendor.
   Локальный сервер должен повторять это, иначе относительные пути врут. */
function buildStaging() {
    const stage = path.join(ROOT, '.e2e-site');
    fs.rmSync(stage, { recursive: true, force: true });
    fs.mkdirSync(stage, { recursive: true });
    const copyDir = (from, to) => {
        fs.mkdirSync(to, { recursive: true });
        for (const f of fs.readdirSync(from)) {
            const s = path.join(from, f), d = path.join(to, f);
            if (fs.statSync(s).isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
        }
    };
    for (const f of ['index.html', 'privacy.html', 'robots.txt', 'sitemap.xml']) {
        fs.copyFileSync(path.join(ROOT, f), path.join(stage, f));
    }
    for (const d of ['css', 'js', 'vendor']) copyDir(path.join(ROOT, d), path.join(stage, d));
    for (const f of fs.readdirSync(path.join(ROOT, 'seo'))) {
        fs.copyFileSync(path.join(ROOT, 'seo', f), path.join(stage, f));
    }
    return stage;
}

const { send } = require('./harness');

/* Открыть страницу с чистым счётчиком конверсий: профиль Chrome живёт между
   прогонами, и без сброса пейволл от прошлого запуска блокирует конвертацию. */
async function freshPage(url) {
    const p = await openPage(url);
    await p.evalJS('localStorage.removeItem("csvtojson_used"); localStorage.removeItem("csvtojson_unlocked");');
    await send('Page.reload', {}, p.sessionId);
    await new Promise((r) => setTimeout(r, 1500));
    return p;
}

