/* Честность обещаний: сайт не имеет права утверждать, что JSON примет портал GST. */
const { ok, read, files } = require('./_harness');

console.log('\n[claims.test.js] обещания на страницах');

const forbidden = [
    'upload it to the portal',
    'upload valid JSON to the portal',
    'valid JSON, and upload',
    'portal-ready'
];

const htmls = ['index.html', 'privacy.html'].concat(files('seo').map(f => 'seo/' + f));
for (const h of htmls) {
    const src = read(h);
    const hits = forbidden.filter(f => src.includes(f));
    ok(`${h}: нет ложного обещания про портал`, hits.length === 0, 'найдено: ' + hits.join(' | '));
}

const gst = read('seo/csv-to-json-for-gst.html');
ok('GST-страница содержит честную оговорку про схему портала',
   gst.includes('own GSTR-1 schema') || gst.includes('schema generated by the Offline Tool'));
