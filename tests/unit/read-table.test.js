/* Excel -> CSV: книга собирается тем же SheetJS, что и на сайте, поэтому тест
   проверяет реальный путь, а не мок. */
const { ok, eq } = require('./_harness');
const XLSX = require('../../vendor/xlsx.full.min.js');
const RT = require('../../js/read-table.js');
const Core = require('../../js/core.js');

console.log('\n[read-table.test.js] Excel -> CSV -> JSON');

// ── фикстура: книга как её отдаёт индийская бухгалтерия ──
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['Title page'], ['Generated by Tally']]), 'Cover');
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
    ['invoice_no', 'hsn', 'taxable', 'party', 'invoice_date'],
    ['00721', '0401', 1500.5, 'Ann, Ltd', new Date(2026, 2, 15)],
    ['00012', '9999', 2000, 'Bo "The Shop"', new Date(2026, 3, 1)],
    [721, 401, 0.5, 'plain', new Date(2026, 4, 9)]
]), 'B2B');
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([]), 'Empty');

ok('имя .xlsx распознаётся', RT.isExcelName('gstr1.xlsx') === true);
ok('имя .xls распознаётся', RT.isExcelName('GSTR1.XLS') === true);
ok('имя .csv не считается Excel', RT.isExcelName('data.csv') === false);
ok('zip-магия PK определяется', RT.isZipMagic([0x50, 0x4b, 0x03, 0x04]) === true);
ok('CSV-файл не проходит как zip', RT.isZipMagic([0x61, 0x2c]) === false);

eq('список листов', wb.SheetNames, ['Cover', 'B2B', 'Empty']);
eq('первый непустой лист выбирается по умолчанию (не титульный)', RT.pickDefaultSheet(XLSX, wb), 1);
ok('пустой лист определяется', RT.isSheetEmpty(RT.sheetRows(XLSX, wb, 2)) === true);
ok('непустой лист не считается пустым', RT.isSheetEmpty(RT.sheetRows(XLSX, wb, 1)) === false);
ok('титульный лист с одной колонкой не считается таблицей', RT.looksLikeTable(RT.sheetRows(XLSX, wb, 0)) === false);
ok('лист с данными считается таблицей', RT.looksLikeTable(RT.sheetRows(XLSX, wb, 1)) === true);
ok('одна колонка, но 5+ строк — тоже данные',
   RT.looksLikeTable([['code'], ['1'], ['2'], ['3'], ['4']]) === true);
ok('две строки — не таблица', RT.looksLikeTable([['a', 'b']]) === false);

const csv = RT.workbookToCsv(XLSX, wb, 1);
ok('CSV содержит заголовки', csv.split('\n')[0].includes('invoice_no'), csv.split('\n')[0]);
ok('текстовый 00721 сохранён как есть', csv.includes('00721'));
ok('поле с запятой закавычено', csv.includes('"Ann, Ltd"'), csv.split('\n')[1]);
ok('кавычки внутри поля удвоены', csv.includes('"Bo ""The Shop"""'), csv.split('\n')[2]);
eq('дата стала YYYY-MM-DD', RT.cellToText(new Date(2026, 2, 15)), '2026-03-15');
ok('дата попала в CSV в человеческом виде', csv.includes('2026-03-15'));
eq('пустая ячейка -> пустая строка', RT.cellToText(''), '');
eq('boolean -> true', RT.cellToText(true), 'true');
eq('null -> пустая строка', RT.cellToText(null), '');

// ── CSV из Excel проходит тот же парсер и то же приведение типов ──
const Papa = require('../../vendor/papaparse.min.js');
const parsed = Papa.parse(csv, { header: true, skipEmptyLines: true, dynamicTyping: false });
eq('PapaParse разобрал все 3 строки данных', parsed.data.length, 3);
const typed = Core.castRows(parsed.data, {});
eq('колонка с ведущим нулём осталась строковой целиком',
   typed.map(r => r.invoice_no), ['00721', '00012', '721']);
eq('HSN: 0401 и 9999 оба строки (колонка не расщепилась)',
   typed.map(r => r.hsn), ['0401', '9999', '401']);
eq('сумма осталась числом', typed.map(r => r.taxable), [1500.5, 2000, 0.5]);
ok('дата осталась строкой ISO', typed[0].invoice_date === '2026-03-15', typed[0].invoice_date);

// ── крайние случаи ──
eq('пустая книга -> пустой CSV', RT.rowsToCsv([]), '');
eq('одна пустая ячейка не даёт лишних кавычек', RT.rowsToCsv([['', 'a']]), ',a');
eq('пробелы по краям закавычиваются', RT.csvField(' pad '), '" pad "');
eq('перевод строки внутри поля закавычен', RT.csvField('a\nb'), '"a\nb"');
