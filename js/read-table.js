/* read-table.js — превращение Excel-книги в CSV-текст, который дальше идёт тем же
 * путём, что и обычный CSV (PapaParse → core.js → JSON).
 *
 * Зачем так: у нас уже есть рабочий конвейер для CSV. Вместо второй ветки парсинга
 * (как было в откаченной версии 08.2026 — три отдельные ветки в preview/single/batch)
 * Excel один раз конвертируется в CSV в момент загрузки файла, и дальше всё одинаково.
 *
 * Файл без DOM: тестируется в node.
 */
(function (root, factory) {
    var api = factory();
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
    if (root) root.CSVtoJSONReadTable = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
    'use strict';

    var EXCEL_NAME = /\.(xlsx|xlsm|xls)$/i;

    function isExcelName(name) {
        return EXCEL_NAME.test(String(name || ''));
    }

    /* xlsx — это zip: первые два байта 'PK'. Проверяем содержимое, а не только имя:
       люди переименовывают .csv в .xlsx и наоборот. */
    function isZipMagic(bytes) {
        return !!bytes && bytes.length >= 2 && bytes[0] === 0x50 && bytes[1] === 0x4b;
    }

    /* Пустой ли лист: нет ни одного непустого значения. */
    function isSheetEmpty(rows) {
        if (!rows || !rows.length) return true;
        for (var r = 0; r < rows.length; r++) {
            var row = rows[r] || [];
            for (var c = 0; c < row.length; c++) {
                var v = row[c];
                if (v !== null && v !== undefined && String(v).trim() !== '') return false;
            }
        }
        return true;
    }

    /* Значение ячейки -> текст. Даты приводим к YYYY-MM-DD: Excel хранит их
       серийным числом, и в JSON попадала бы каша. */
    function cellToText(value) {
        if (value === null || value === undefined) return '';
        if (value instanceof Date) {
            if (isNaN(value.getTime())) return '';
            var y = value.getFullYear();
            var m = String(value.getMonth() + 1).padStart(2, '0');
            var d = String(value.getDate()).padStart(2, '0');
            return y + '-' + m + '-' + d;
        }
        if (typeof value === 'boolean') return value ? 'true' : 'false';
        return String(value);
    }

    /* Лист -> массив массивов. header:1 сохраняет первую строку как данные,
       defval:'' — пустые ячейки вместо дырок.
       raw:true — берём исходные значения (числа остаются числами, текст текстом). */
    function sheetRows(XLSX, workbook, sheetIndex) {
        var name = workbook.SheetNames[sheetIndex];
        if (!name) return [];
        var ws = workbook.Sheets[name];
        if (!ws) return [];
        return XLSX.utils.sheet_to_json(ws, { header: 1, raw: true, defval: '', blankrows: false });
    }

    /* Похож ли лист на таблицу данных. В выгрузках Tally/1С первый лист часто
       титульный: одна колонка текста («Generated by Tally»), и открывать книгу
       на нём бессмысленно. */
    function looksLikeTable(rows) {
        if (!rows || rows.length < 2) return false;
        var width = 0;
        for (var c = 0; c < (rows[0] || []).length; c++) {
            if (String(rows[0][c] === undefined ? '' : rows[0][c]).trim() !== '') width++;
        }
        if (width >= 2) return true;
        // узкий, но длинный список (одна колонка кодов) — тоже данные
        return width === 1 && rows.length >= 5;
    }

    /* Индекс листа по умолчанию: первый лист, похожий на таблицу. Если таких нет —
       первый непустой, иначе 0. */
    function pickDefaultSheet(XLSX, workbook) {
        var i, rows;
        for (i = 0; i < workbook.SheetNames.length; i++) {
            rows = sheetRows(XLSX, workbook, i);
            if (looksLikeTable(rows)) return i;
        }
        for (i = 0; i < workbook.SheetNames.length; i++) {
            if (!isSheetEmpty(sheetRows(XLSX, workbook, i))) return i;
        }
        return 0;
    }

    /* Экранирование одного поля CSV: кавычки, запятые, переводы строк, краевые пробелы. */
    function csvField(text) {
        var s = String(text);
        if (s === '') return '';
        var needsQuote = /[",\r\n]/.test(s) || /^\s|\s$/.test(s);
        if (!needsQuote) return s;
        return '"' + s.replace(/"/g, '""') + '"';
    }

    /* Массив массивов -> CSV. Разделитель по умолчанию запятая (PapaParse определит авто). */
    function rowsToCsv(rows, delimiter) {
        var sep = delimiter || ',';
        return (rows || []).map(function (row) {
            return (row || []).map(function (cell) { return csvField(cellToText(cell)); }).join(sep);
        }).join('\n');
    }

    /* Полный путь: книга -> CSV-текст выбранного листа. */
    function workbookToCsv(XLSX, workbook, sheetIndex) {
        return rowsToCsv(sheetRows(XLSX, workbook, sheetIndex));
    }

    return {
        isExcelName: isExcelName,
        isZipMagic: isZipMagic,
        isSheetEmpty: isSheetEmpty,
        cellToText: cellToText,
        sheetRows: sheetRows,
        looksLikeTable: looksLikeTable,
        pickDefaultSheet: pickDefaultSheet,
        csvField: csvField,
        rowsToCsv: rowsToCsv,
        workbookToCsv: workbookToCsv,
        version: '1.0.0'
    };
});
